//! The glass as a Hyprland screen shader: FS_GLASS of ybouane/liquidglass, ported to GLSL ES 3.0
//! and run by the compositor over each frame it has just composited.
//!
//! That is what makes it instant: the shader samples the very frame it is drawing on, so what is
//! behind the glass is never a capture of an earlier frame, and nothing runs on the GPU unless
//! Hyprland is drawing a frame anyway. Where the glass is comes from the [`marker`](crate::marker)
//! strip; the look is baked in as constants (a new look is a new shader).
//!
//! Per pixel outside the glass the cost is two texel fetches: the magic block and, past it, the
//! glass's bounding box.

use std::fmt::Write as _;

use crate::config::{Bevel, GlassConfig, SHADOW_PAD};
use crate::marker::{BLOCK, BLOCKS, MAGIC, MAX_OCCLUDERS};

/// The shader for `glass`, knowing each monitor's scale (by Hyprland monitor ID, which is what
/// the shader's `wl_output` holds).
pub fn glsl(glass: &GlassConfig, scales: &[(i64, f64)]) -> String {
    let mut scale_of = String::new();
    for (id, s) in scales {
        let _ = writeln!(scale_of, "    if (o == {id}) return {s:.7};");
    }
    let f = |v: f32| format!("{v:.6}");
    let constants = [
        ("PAD", f(SHADOW_PAD)),
        ("RADIUS", f(glass.corner_radius)),
        ("Z_RADIUS", f(glass.z_radius)),
        ("REFRACT", f(glass.refraction)),
        ("CHROMA", f(glass.chrom_aberration)),
        ("EDGE_HL", f(glass.edge_highlight)),
        ("SPEC", f(glass.specular)),
        ("FRESNEL", f(glass.fresnel)),
        ("DISTORT", f(glass.distortion)),
        ("ALPHA", f(glass.opacity)),
        ("SAT", f(glass.saturation)),
        ("TINT", f(glass.tint_strength)),
        ("BRIGHTNESS", f(glass.brightness)),
        ("SHADOW_ALPHA", f(glass.shadow_opacity)),
        ("SHADOW_SPREAD", f(glass.shadow_spread)),
        ("SHADOW_OFF_Y", f(glass.shadow_offset_y)),
        ("BLUR", f(glass.blur_amount)),
        ("BUTTON", f(if glass.button { 1.0 } else { 0.0 })),
        ("BEVEL_MODE", f(match glass.bevel {
            Bevel::Pill => 0.0,
            Bevel::Dome => 1.0,
        })),
    ];
    let mut consts = String::new();
    for (name, value) in constants {
        let _ = writeln!(consts, "const float {name} = {value};");
    }
    TEMPLATE
        .replace("{CONSTS}", &consts)
        .replace("{SCALE_OF}", &scale_of)
        .replace("{BLOCK}", &format!("{:.1}", f64::from(BLOCK)))
        .replace("{BLOCKS}", &BLOCKS.to_string())
        .replace("{MAX_OCC}", &MAX_OCCLUDERS.to_string())
        .replace("{MAGIC}", &format!("ivec3({}, {}, {})", MAGIC[0], MAGIC[1], MAGIC[2]))
}

const TEMPLATE: &str = r#"#version 300 es
// liquid-glass: iOS 26 liquid glass as a screen shader. Generated by the liquid-glass app,
// which puts your previous screen shader back when it quits.
precision highp float;
// Integers default to mediump in fragment shaders, which may be 16 bits: the marker's 24-bit
// numbers would overflow.
precision highp int;
in vec2 v_texcoord;
uniform sampler2D tex;
uniform int wl_output;
uniform vec2 fullSize;
out vec4 fragColor;

{CONSTS}
const float BLOCK = {BLOCK};
const int BLOCKS = {BLOCKS};
const int MAX_OCC = {MAX_OCC};

float scale_of(int o) {
{SCALE_OF}    return 1.0;
}

// One block of the marker strip, as bytes.
ivec3 block(int i, float s) {
    vec2 p = floor(vec2((float(i) + 0.5) * BLOCK * s, 0.5 * BLOCK * s));
    return ivec3(round(texelFetch(tex, ivec2(p), 0).rgb * 255.0));
}

float number(int i, float s) {
    ivec3 c = block(i, s);
    return float(((c.r << 16) | (c.g << 8) | c.b) - 8388608);
}

float rr_sdf(vec2 p, vec2 b, float r) {
    vec2 q = abs(p) - b + vec2(r);
    return min(max(q.x, q.y), 0.0) + length(max(q, vec2(0.0))) - r;
}

// Half-circle profile: smooth at the top, steep at the edge. d = distance in from the edge.
float bevel_height(float d, float z_r) {
    if (d <= 0.0) return 0.0;
    if (d >= z_r) return z_r;
    return sqrt(d * (2.0 * z_r - d));
}

float hash(vec2 p) {
    return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453);
}

vec3 sample3(vec2 base, vec2 ca) {
    return vec3(
        texture(tex, (base + ca) / fullSize).r,
        texture(tex, base / fullSize).g,
        texture(tex, (base - ca) / fullSize).b
    );
}

// The frame has no mip chain: where the bevel squeezes several pixels into one, average a few
// samples across the footprint so text there is filtered rather than aliased.
vec3 sample_footprint(vec2 base, vec2 ca, vec2 dx, vec2 dy) {
    float f = max(length(dx), length(dy));
    if (f < 1.5) return sample3(base, ca);
    vec3 acc = vec3(0.0);
    acc += sample3(base + 0.375 * dx + 0.125 * dy, ca);
    acc += sample3(base - 0.375 * dx - 0.125 * dy, ca);
    acc += sample3(base + 0.125 * dx - 0.375 * dy, ca);
    acc += sample3(base - 0.125 * dx + 0.375 * dy, ca);
    return acc * 0.25;
}

vec3 blurred(vec2 base, vec2 ca) {
    // 12-tap disc, radius BLUR × 12 px.
    const vec2 DISC[12] = vec2[12](
        vec2(-0.326, -0.406), vec2(-0.840, -0.074), vec2(-0.696, 0.457), vec2(-0.203, 0.621),
        vec2(0.962, -0.195), vec2(0.473, -0.480), vec2(0.519, 0.767), vec2(0.185, -0.893),
        vec2(0.507, 0.064), vec2(0.896, 0.412), vec2(-0.322, -0.933), vec2(-0.792, -0.598)
    );
    vec3 acc = vec3(0.0);
    for (int i = 0; i < 12; i++) acc += sample3(base + DISC[i] * BLUR * 12.0, ca);
    return acc / 12.0;
}

void main() {
    vec4 c = texture(tex, v_texcoord);
    fragColor = c;
    float s = scale_of(wl_output);
    if (block(0, s) != {MAGIC}) return;

    // Pixel centres, y down (v_texcoord already lands on them).
    vec2 px = v_texcoord * fullSize;

    // The strip itself: show what is just below it instead.
    vec2 strip = vec2(ceil(float(BLOCKS) * BLOCK * s) + 1.0, ceil(BLOCK * s) + 1.0);
    if (px.x < strip.x && px.y < strip.y) {
        fragColor = texelFetch(tex, ivec2(int(px.x), int(strip.y) + 1), 0);
        return;
    }

    vec4 win = vec4(number(1, s), number(2, s), number(3, s), number(4, s));
    if (px.x < win.x || px.y < win.y || px.x >= win.x + win.z || px.y >= win.y + win.w) return;

    // Only now, inside the glass's box: the checksum, the state and the windows above it.
    int sum = 0;
    int xr = 0;
    for (int i = 1; i < BLOCKS - 1; i++) {
        ivec3 b = block(i, s);
        sum += b.r + b.g + b.b;
        xr ^= b.r ^ b.g ^ b.b;
    }
    if (block(BLOCKS - 1, s) != ivec3(sum & 255, xr, 165)) return;
    ivec3 st = block(5, s);
    if ((st.b & 1) == 0) return;
    for (int i = 0; i < MAX_OCC; i++) {
        vec4 o = vec4(number(6 + 4 * i, s), number(7 + 4 * i, s), number(8 + 4 * i, s), number(9 + 4 * i, s));
        if (px.x >= o.x && px.y >= o.y && px.x < o.x + o.z && px.y < o.y + o.w) return;
    }
    float press = float(st.r) / 255.0 * BUTTON;
    float hover = float(st.g) / 255.0 * BUTTON;

    // Upstream's button states: hover brightens, a press flattens the bevel and spreads the
    // shadow, dropping the hover boost.
    float brightness = BRIGHTNESS + 0.2 * hover * (1.0 - press);
    float spread = max(SHADOW_SPREAD * s * (1.0 + 0.2 * press), 1.0);

    vec2 half_ = max(win.zw * 0.5 - vec2(PAD * s), vec2(1.0));
    vec2 local = px - (win.xy + win.zw * 0.5);
    float r = min(RADIUS * s, min(half_.x, half_.y));
    // The lens scales with the glass. Upstream's bevel depth and bend distances are tuned for
    // panels a few hundred px across; on a small glass they would be wider than the glass
    // itself, the whole surface would be steep bevel, and every pixel would sample from far
    // outside (mirrored text, or everything squeezed into a line). Below 1.5 bevel depths of
    // half-size, the bevel and every distance it bends by shrink in proportion, so a small glass
    // keeps a flat, sharp middle and a thin bending rim.
    float lens = clamp(min(half_.x, half_.y) / (Z_RADIUS * s * 1.5), 0.05, 1.0);
    float z_r = Z_RADIUS * s * lens * (1.0 - 0.2 * press);
    float sdf = rr_sdf(local, half_, r);

    // ── Shadow (outside the panel, offset down) ──
    float sdf_shadow = rr_sdf(local - vec2(0.0, SHADOW_OFF_Y * s), half_, r);
    float ds = max(sdf_shadow - 1.0, 0.0);
    float outer_shadow = exp(-ds * ds / (spread * spread)) * 0.65;
    float contact_shadow = exp(-ds * 0.08 / max(spread * 0.04, 0.01)) * 0.35;
    float shadow = (outer_shadow + contact_shadow) * SHADOW_ALPHA;
    vec3 under = c.rgb * (1.0 - (sdf > 0.0 ? shadow : 0.0));
    if (sdf > 0.5) {
        fragColor = vec4(under, c.a);
        return;
    }

    // ── Anti-aliased mask ──
    float mask = 1.0 - smoothstep(-1.5, 0.5, sdf);
    float max_d = min(half_.x, half_.y);
    float inside = -sdf;
    float edge = 1.0 - smoothstep(0.0, max_d * 0.35, inside);

    // ── Surface normal from the bevel height field ──
    // The normal's finite-difference step, small enough for a thin bevel.
    float e = clamp(z_r * 0.05, 0.5, 2.0);
    float h_c = bevel_height(inside, z_r);
    float h_r = bevel_height(-rr_sdf(local + vec2(e, 0.0), half_, r), z_r);
    float h_l = bevel_height(-rr_sdf(local - vec2(e, 0.0), half_, r), z_r);
    float h_u = bevel_height(-rr_sdf(local + vec2(0.0, e), half_, r), z_r);
    float h_d = bevel_height(-rr_sdf(local - vec2(0.0, e), half_, r), z_r);
    vec2 h_grad = vec2(h_r - h_l, h_u - h_d) / (2.0 * e);
    vec3 n = normalize(vec3(-h_grad, 1.0));
    float depth = smoothstep(0.0, z_r, inside);

    // ── Refraction ──
    float refr_pow = 1.0 - 1.0 / 1.5;
    float thick_norm = h_c * 2.0 / max(z_r * 2.0, 1.0);
    vec2 refr_px;
    if (BEVEL_MODE < 0.5) {
        // Biconvex: light bends entering the bottom surface and leaving the top.
        vec2 exit_refr = h_grad * refr_pow;
        vec2 entry_refr = h_grad * refr_pow;
        refr_px = (exit_refr + entry_refr + entry_refr * thick_norm * 0.5) * REFRACT * 30.0 * lens;
        refr_px += -local / max(half_, vec2(1.0)) * REFRACT * 4.0 * depth * lens;
    } else {
        // Dome: magnify by pulling samples toward the centre.
        refr_px = -local * REFRACT * depth * 0.35;
    }

    // ── Micro-distortion, chromatic aberration ──
    vec2 ns = local * 0.08;
    vec2 micro = (vec2(hash(ns), hash(ns + vec2(37.0))) - 0.5) * DISTORT * 4.0;
    vec2 ca = n.xy * CHROMA * 18.0 * (edge * 0.7 + 0.3) * 2.0 * lens;
    vec2 base = px + refr_px + micro;

    vec3 col = sample_footprint(base, ca, dFdx(base), dFdy(base));
    if (BLUR > 0.0) {
        // The centre takes the blurred sample, the rim leans sharp so its bends stay crisp.
        col = mix(col, blurred(base, ca), 1.0 - edge * 0.15);
    }

    // ── Brightness, saturation, tint ──
    col *= 1.0 + brightness;
    float lum = dot(col, vec3(0.299, 0.587, 0.114));
    col = mix(vec3(lum), col, 1.0 + SAT);
    col = mix(col, col * vec3(0.92, 0.95, 1.05), TINT);
    col *= 1.0 + 0.06 * depth;

    // ── Fresnel and multi-light Blinn-Phong ──
    float fres = pow(1.0 - abs(n.z), 4.0) * FRESNEL;
    vec3 v = vec3(0.0, 0.0, 1.0);
    float sp1 = pow(max(dot(n, normalize(normalize(vec3(0.4, 0.7, 1.0)) + v)), 0.0), 90.0);
    float sp2 = pow(max(dot(n, normalize(normalize(vec3(-0.3, -0.5, 1.0)) + v)), 0.0), 50.0) * 0.3;
    float sp_b = pow(max(dot(n, normalize(vec3(0.1, 0.3, 1.0))), 0.0), 6.0) * 0.1;
    float sp4 = pow(max(dot(n, normalize(normalize(vec3(0.0, 0.9, 0.4)) + v)), 0.0), 120.0) * 0.6;
    float total_spec = (sp1 + sp2 + sp_b + sp4) * SPEC;

    // ── Inner stroke (brighter along the top), rim, inner glow, fake environment ──
    float inner_stroke = smoothstep(-2.5, -1.5, sdf) * (1.0 - smoothstep(-1.0, 0.0, sdf));
    inner_stroke *= 0.4 + 0.6 * (0.5 + 0.5 * (-local.y / half_.y));
    float rim = edge * EDGE_HL * 0.22;
    float inner_glow = (1.0 - smoothstep(0.0, 5.0, -sdf)) * EDGE_HL * 0.15;
    float env_refl = (n.y * 0.5 + 0.5) * fres * 0.08;

    vec3 fin = col + vec3(total_spec + rim + inner_glow + inner_stroke * EDGE_HL * 0.55 + env_refl);
    fin = mix(fin, vec3(1.0), fres * 0.2);
    fin = clamp(fin, 0.0, 1.0);

    fragColor = vec4(mix(under, fin, mask * ALPHA), c.a);
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_look_and_the_monitor_scales_are_baked_in() {
        let glass = GlassConfig { refraction: 0.8, ..GlassConfig::default() };
        let text = glsl(&glass, &[(0, 4.0 / 3.0), (1, 2.0)]);
        assert!(text.starts_with("#version 300 es\n"), "Hyprland picks its vertex shader by this line");
        assert!(text.contains("const float REFRACT = 0.800000;"));
        assert!(text.contains("if (o == 0) return 1.3333333;"));
        assert!(text.contains("if (o == 1) return 2.0000000;"));
        assert!(text.contains("ivec3(76, 71, 33)"), "the magic block");
        assert!(text.contains("precision highp int;"), "24-bit numbers need 32-bit ints");
        assert!(text.contains("float z_r = Z_RADIUS * s * lens"), "a small glass needs a smaller bevel, or it is all bevel");
        assert!(text.contains("REFRACT * 30.0 * lens"), "and shorter bends, or it samples from far outside itself");
        for placeholder in ["{CONSTS}", "{SCALE_OF}", "{BLOCK}", "{BLOCKS}", "{MAX_OCC}", "{MAGIC}"] {
            assert!(!text.contains(placeholder), "{placeholder} left in");
        }
    }
}
